import 'package:flutter/foundation.dart';
import '../data_sources/remote/ai_api.dart';
import '../data_sources/remote/supabase_api.dart';
import '../data_sources/local/local_storage.dart';
import '../models/correction_request.dart';
import '../models/chat_session_model.dart';

class CorrectionRepository {
  final AIApi _aiApi;
  final SupabaseApi _supabaseApi;
  final AppLocalStorage _localStorage;

  CorrectionRepository(
    this._aiApi,
    this._supabaseApi,
    this._localStorage,
  );

  /// Correct text using AI
  Future<String> correctText(CorrectionRequest request) async {
    final response = await _aiApi.correctText(request);
    return response.corrected;
  }

  /// Save chat session to database and local storage.
  ///
  /// [source] says where the correction was made (see [ChatSessionModel]);
  /// [createdAt] and [localId] are set for keyboard corrections, which are
  /// saved later than they were made. A [localId] already in local history
  /// is skipped, so a keyboard correction is never added twice.
  Future<void> saveChatSession({
    required String userId,
    required String correctedText,
    required String inputText,
    required String language,
    required String model,
    String source = ChatSessionModel.sourceApp,
    DateTime? createdAt,
    String? localId,
  }) async {
    final chatHistory = _localStorage.getChatHistory();
    if (localId != null && chatHistory.any((item) => item['id'] == localId)) {
      return;
    }

    final session = ChatSessionModel(
      id: '', // Will be generated by database
      userId: userId,
      correctedText: correctedText,
      inputText: inputText,
      language: language,
      model: model,
      createdAt: createdAt,
      source: source,
    );

    // Save to database if user is authenticated
    if (userId.isNotEmpty) {
      try {
        await _supabaseApi.saveChatSession(session);
      } catch (e) {
        // If database save fails, still save locally
        debugPrint('Failed to save to database: $e');
      }
    }

    // Always save to local storage
    final now = DateTime.now();
    chatHistory.insert(0, {
      'id': localId ?? now.millisecondsSinceEpoch.toString(),
      'correctedText': correctedText,
      'inputText': inputText,
      'language': language,
      'model': model,
      'createdAt': (createdAt ?? now).toIso8601String(),
      'source': source,
    });

    // Newest first (keyboard corrections can be older than ones made since).
    chatHistory.sort(
      (a, b) => (b['createdAt'] as String? ?? '')
          .compareTo(a['createdAt'] as String? ?? ''),
    );

    // Keep only last 100 items
    if (chatHistory.length > 100) {
      chatHistory.removeRange(100, chatHistory.length);
    }

    await _localStorage.saveChatHistory(chatHistory);
  }

  /// Get chat history
  Future<List<ChatSessionModel>> getChatHistory(String? userId) async {
    if (userId != null && userId.isNotEmpty) {
      try {
        // Get from database if authenticated
        return await _supabaseApi.getChatSessions(userId);
      } catch (e) {
        debugPrint('Failed to fetch from database: $e');
      }
    }

    // Fall back to local storage
    final localHistory = _localStorage.getChatHistory();
    return localHistory
        .map((json) => ChatSessionModel(
              id: json['id'] ?? '',
              userId: userId ?? '',
              correctedText: json['correctedText'] ?? '',
              inputText: json['inputText'] ?? '',
              language: json['language'] ?? 'english',
              model: json['model'] ?? 'gpt-3.5-turbo',
              createdAt: json['createdAt'] != null
                  ? DateTime.parse(json['createdAt'])
                  : null,
              source: json['source'] ?? ChatSessionModel.sourceApp,
            ),)
        .toList();
  }
}

